def R(ings, include=None, exclude=RB.NONORAL, exact=True, drop=None, limit=100):
    ex = KIDS + ("|" + drop if drop else "")
    out = RB.brands(ings, include=include, exclude=exclude, exact=exact, extra_exclude=ex)
    return out[:limit]


HE_ING = {"PARACETAMOL": "פרצטמול", "IBUPROFEN": "איבופרופן", "LORATADINE": "לורטדין", "CHLORPHENIRAMINE": "כלורפנירמין",
          "DEXCHLORPHENIRAMINE": "דקסכלורפנירמין", "TRIPROLIDINE": "טריפרולידין", "DIPHENHYDRAMINE": "דיפנהידרמין",
          "DEXTROMETHORPHAN": "דקסטרומתורפן", "GUAIFENESIN": "גואיפנזין"}


def with_partners(brands, main):
    """Note on each brand which other active ingredients it contains (from the registry), e.g. "עם פרצטמול"."""
    for b in brands:
        ings = set()
        for en, he, ing, _ in RB._ROWS:
            if RB._base(en).lower() == b["en"].lower():
                ings |= {w for w in HE_ING if w in ing.upper() and not ("DEXCHLORPHENIRAMINE" in ing.upper() and w == "CHLORPHENIRAMINE")}
        b["note"] = ("עם " + ", ".join(HE_ING[w] for w in sorted(ings, key=list(HE_ING).index))) if ings else main + " בלבד"
    return brands


def N(k, label, det, bad, urgent=False):
    """One check of a non-chronic request: not met → the request goes to the physician with the finding."""
    return dict(k=k, label=label, det=det, doc=label + ".", bad=bad + (" — דחוף" if urgent else ""), opt=False,
                crit=det + ". לא ← לרופא/ה עם הבקשה" + (", בדחיפות" if urgent else "") + ".")


def checks(dur, flags, extra=(), preg=True, preg_det="אין היריון או הנקה ברשומה או בפנייה"):
    c = [N("age18", "גיל 18 ומעלה", "המטופל/ת בן/בת 18 ומעלה", "מתחת לגיל 18")]
    if preg:
        c.append(N("preg", "לא בהיריון ולא מניקה", preg_det, "היריון או הנקה"))
    c.append(N("allergy", "אין רגישות לתרופה", "ברשומה אין רגישות לתרופה או לקבוצה שלה", "רגישות לתרופה ברשומה"))
    c += list(extra)
    # interaction and quantity checks are added to every drug by handover.py
    c.append(N("dur", "משך וכמות בגבולות", dur, "בקשה לטיפול ארוך או לכמות גדולה יותר, או בקשות חוזרות תכופות"))
    c.append(N("flags", "אין סימני אזהרה בפנייה", flags, "סימן אזהרה בפנייה", urgent=True))
    return c


def O(generic, he, cls, brands, why, chk, patnote, comp=(), **kw):
    seen, uniq = set(), []
    for b in brands:
        if b["en"].upper() not in seen:
            seen.add(b["en"].upper()); uniq.append(b)
    d = dict(generic=generic, he=he, cls=cls, brands=uniq, suit="הכנה", why=why, labs="-", thr=["-"], severe=[], excl=[],
             comp=list(comp), src=kw.pop("src", SRC), checks=chk, doctitle=TITLE, patnote=patnote, tab="nonchronic")
    d.update(kw)
    return d


def cat(he):
    return "קורס קצר · " + he


