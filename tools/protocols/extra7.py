    names = {d["generic"] for d in allp}
    for g in BRANDS:
        assert g in names, "extra7: no entry " + g
    for d in allp:
        have = {b["en"].lower() for b in d["brands"]}
        for b in BRANDS.get(d["generic"], []):
            if b["en"].lower() not in have:
                d["brands"].append(b); have.add(b["en"].lower())
    lists[-1].extend(NEW)
