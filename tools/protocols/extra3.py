def mdrug(*a, **k):
    d = _M.drug(*a, **k)
    d["checks"] = _M._checks(d)
    del d["_t"]
    if d["suit"] == "בתנאים":
        d["cond"] = d.get("cond_det", _M.CHRONIC)
        d["why"] = "רק " + d["cond"] + ". " + d["why"]
    if d["severe"]:
        d["excl_x"] = d["excl"] + ["ערך חמור: " + "; ".join(d["severe"])]
    d["cls"] = d["area"] + " · " + d["cls"]
    return d
