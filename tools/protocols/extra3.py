def RBL(ings, drop=None, cap=40):
    out, seen = [], set()
    for i in ings:
        for b in RB.brands([i], exclude=None, exact=False):
            k = b["en"].lower()
            if k in seen or (drop and any(x in k for x in drop)):
                continue
            seen.add(k); out.append(b)
    return out[:cap]

