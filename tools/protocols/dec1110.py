def empty(x):
    x = str(x).strip()
    return x in ("", "-", "—") or "לא מופיע" in x


def apply(ALL):
    n = left = 0
    for k in ALL.get("order", []):
        decs = ALL[k].get("decisions", []) or []
        for i, d in enumerate(decs):
            d = decs[i] = list(d)
            if not empty(d[2]):
                continue
            g = GT.get((k, d[1])) or G.get(d[1])
            if d[1] == "תרופות עם כמה התוויות" and str(d[0]).startswith("סוכרת"):
                g = ("SGLT2i (דפגליפלוזין, אמפגליפלוזין) ב-CKD ובאי ספיקת לב: התחלה עד eGFR ≥20 והמשך עד דיאליזה; GLP-1/טירזפטייד "
                     "בהתוויה למשקל או ללב — לא תלוי HbA1c", "ADA 2026; KDIGO 2024")
            if d[1] == "בדיקות מעקב" and k in ("neuro", "psych") and str(d[0]).startswith("נוירו"):
                g = ("אוקסקרבזפין: נתרן (עלון); פניטואין: טווח 10-20 mg/L (עלון); תרופות שמופרשות בכליות: מינון לפי תפקוד כלייתי", "עלונים")
            if not g or not g[0]:
                left += 1
                continue
            d[2] = g[0]
            if g[1] and g[1] not in str(d[5]):
                d[5] = (str(d[5]).strip(" —-") + "; " if str(d[5]).strip(" —-") else "") + g[1]
            n += 1
    return n, left


