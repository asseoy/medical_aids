def empty(x):
    x = str(x).strip()
    return x in ("", "-", "—") or "לא מופיע" in x


def apply(ALL):
    n = left = 0
    for k in ALL.get("order", []):
        decs = ALL[k].get("decisions", []) or []
        for i, d in enumerate(decs):
            d = decs[i] = list(d)
            if not empty(d[2]):
                continue
            g = GT.get((k, d[1])) or G.get(d[1])
            if d[1] == "תרופות עם כמה התוויות" and str(d[0]).startswith("סוכרת"):
                g = ("SGLT2i ב-CKD ובאי ספיקת לב: התחלה מ-eGFR ≥20; ב-eGFR 20-45 ממשיכים עד דיאליזה או השתלה (KDIGO 2024; ADA 2026). "
                     "GLP-1 ו-SGLT2i בסיכון קרדיווסקולרי — ללא תלות ב-HbA1c (ADA 2026, 9.7)", "ADA 2026; KDIGO 2024")
            if d[1] == "בדיקות מעקב" and k in ("neuro", "psych") and str(d[0]).startswith("נוירו"):
                g = ("אוקסקרבזפין: נתרן לפני (בסיכון), אחרי שבועיים ואז חודשי ל-3 חודשים (עלון). פניטואין: רמה שגרתית לא מומלצת; טווח 10-20 mg/L (SPS)", "עלון אוקסקרבזפין; SPS")
            if not g or not g[0]:
                left += 1
                continue
            d[2] = g[0]
            if d[1] in PROTO and k not in ("cert", "req", "vac"):
                d[3] = PROTO[d[1]]
            if g[1] and g[1] not in str(d[5]):
                d[5] = (str(d[5]).strip(" —-") + "; " if str(d[5]).strip(" —-") else "") + g[1]
            n += 1
    return n, left


