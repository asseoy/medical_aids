def D(generic, he, cls, brands, why, labs, checks, thr=(), severe=(), excl=(), comp=(), suit="בתנאים", src=NA, **kw):
    d = dict(generic=generic, he=he, cls=cls, brands=brands, suit=suit, why=why, labs=labs, thr=list(thr) or ["אין ערך מעבדה ייעודי"],
             severe=list(severe), excl=list(excl), comp=list(comp), src=src, checks=checks)
    if d["severe"] or d["excl"]:
        d["excl_x"] = d["excl"] + (["ערך חמור: " + "; ".join(d["severe"])] if d["severe"] else [])
    if suit == "בתנאים":
        d["cond"] = "טיפול כרוני במינון קבוע"
    d.update(kw)
    return d


