def B(en, he, note=""):
    return dict(en=en, he=he, note=note)


def mon(k, label, det, clinic):
    return dict(k=k, label=label, det=det, doc=label + ": " + det + ".", clinic=clinic, opt=False,
                crit=det + ". אין ← חידוש לחודש אחד וזימון לבדיקה.")


def dev(k, label, det, bad, urgent=False):
    return dict(k=k, label=label, det=det, doc=label + ".", bad=bad + (" — דחוף" if urgent else ""), opt=False,
                crit=det + ". לא ← חידוש לחודש אחד והודעה" + (" דחופה" if urgent else "") + " לרופא/ה.")


def contra(k, label, det, bad):
    return dict(k=k, label=label, det=det, doc=label + ".", bad=bad, contra=True, opt=False,
                crit=det + ". לא ← התווית נגד: לא מחדשים, הודעה דחופה לרופא/ה.")


def opt(k, label, q, det, bad):
    return dict(k=k, label=label, q=q, det=det, doc=label + ": " + det + ".", bad=bad, opt=True,
                crit=det + ". לא ← חידוש לחודש אחד והודעה לרופא/ה.")


