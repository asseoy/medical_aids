def _set(d, upd):
    d.pop("only", None)
    d.update(copy.deepcopy(upd))
    d["cls"] = d["cls"].replace("רופא/ה בלבד · ", "").replace(" · רופא/ה", "").replace("רופא/ה בלבד", "הכנה לרופא/ה")


def apply(lists):
    allp = [d for L in lists for d in L]
    by = {d["generic"]: d for d in allp}
    for g, upd in DECISIONS.items():
        assert g in by, "review1107: no entry " + g
        assert by[g]["suit"] == "לא", "review1107: not physician-only " + g
        _set(by[g], upd)
    # IV iron was already "prepare"; it now carries the red flag
    iv = by["Intravenous iron"]
    assert iv["suit"] == "הכנה"
    iv["red"] = True
    iv["why"] = "ברזל בעירוי: הרפואן מכין את ההפניה, והרופא/ה מאשר/ת לפני השליחה (דגל אדום). " + iv["why"]
    # strep exception next to "antibiotics for a new symptom" (which stays with the physician)
    for L in lists:
        for i, d in enumerate(L):
            if d["generic"] == "Antibiotics for a new symptom":
                st = copy.deepcopy(STREP)
                st["brands"] = [b for b in d["brands"] if b["en"].lower().startswith(("moxypen", "pen-rafa"))]
                assert st["brands"], "review1107: no Moxypen/Rafapen brands"
                d["why"] = d["why"] + " חריג: מוקסיפן או רפאפן אחרי משטח גרון חיובי — בפריט נפרד."
                L.insert(i + 1, st)
                break
    # immunoglobulins: tetanus and anti-D become separate regular entries; rabies is removed (not the assistant's work)
    for L in lists:
        for i, d in enumerate(L):
            if d["generic"] == "Immunoglobulins":
                tet, ad = copy.deepcopy(d), copy.deepcopy(d)
                tet["brands"] = [b for b in d["brands"] if "hypertet" in b["en"].lower()]
                ad["brands"] = [b for b in d["brands"] if "rho" in b["en"].lower()]
                assert tet["brands"] and ad["brands"]
                for x, upd in ((tet, TETANUS), (ad, ANTID)):
                    x.pop("only", None); x.pop("mixed", None)
                    x.update(copy.deepcopy({k: v for k, v in upd.items() if v is not None}), src=SRC, labs="-",
                             doctitle="מרשם לאימונוגלובולין")
                    x["cls"] = "אימונוגלובולינים"
                L[i:i + 1] = [tet, ad]
                break
    # split MS: Copaxone becomes its own regular entry
    for L in lists:
        for i, d in enumerate(L):
            if d["generic"] == "Multiple sclerosis drugs":
                cop = copy.deepcopy(d)
                cop.update(generic="Glatiramer (MS)", he="גלטירמר לטרשת נפוצה (קופקסון)",
                           brands=[b for b in d["brands"] if "copaxone" in b["en"].lower() or "glatiramer" in b["en"].lower()], tab="neuro")
                cop.pop("mixed", None)
                d["brands"] = [b for b in d["brands"] if b not in cop["brands"]]
                _set(d, MS_RED); _set(cop, MS_REG)
                L.insert(i + 1, cop)
                return
    raise AssertionError("review1107: no MS entry")


