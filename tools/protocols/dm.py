def drug(generic, he, kinds, brands, suit="כן", why="", thr=None, severe=None, excl=None, comp=None, src=None, cls=None):
    """kinds: one or more class keys (combos take the union)."""
    ts = [T[k] for k in kinds]
    u = lambda key: list(dict.fromkeys(x for t in ts for x in t[key]))
    d = dict(generic=generic, he=he, kinds=list(kinds),
             cls=cls or " + ".join(t["cls"] for t in ts),
             brands=brands, suit=suit, why=why,
             thr=thr if thr is not None else [x for x in u("thr") if x != "אין ערך מעבדה ייעודי"] or ["אין ערך מעבדה ייעודי"],
             severe=severe if severe is not None else u("severe"),
             excl=excl if excl is not None else u("excl"),
             comp=comp if comp is not None else [c for t in ts for c in t["comp"]],
             labs=ts[0]["labs"] if len(ts) == 1 else "; ".join(dict.fromkeys(t["labs"] for t in ts)),
             src=src or "; ".join(dict.fromkeys(t["src"] for t in ts)))
    return d


