def B(*pairs):
    """brands: tuples (english, hebrew, note)"""
    out = []
    for p in pairs:
        en, he = p[0], p[1]
        note = p[2] if len(p) > 2 else ""
        out.append({"en": en, "he": he, "note": note})
    return out


def drug(cls, generic, he, brands, tpl, suit, why, src, labs=None, thr=None, comp=None, excl=None):
    return dict(cls=cls, generic=generic, he=he, brands=brands,
                labs=labs or tpl["labs"], thr=thr or tpl["thr"], comp=comp or tpl["comp"],
                excl=excl or tpl["excl"], suit=suit, why=why, src=src)


def combo(cls, generic, he, brands, a, b, suit, why, src):
    return dict(cls=cls, generic=generic, he=he, brands=brands,
                labs=a["labs"] if a is not CCB else b["labs"],
                thr=list(dict.fromkeys(a["thr"] + ([] if b is CCB else b["thr"]))),
                comp=a["comp"] + b["comp"], excl=list(dict.fromkeys(a["excl"] + b["excl"])),
                suit=suit, why=why, src=src)


