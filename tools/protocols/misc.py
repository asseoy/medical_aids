def drug(generic, he, kinds, brands, suit="כן", why="", cls=None, **over):
    ts = [T[k] for k in kinds]
    u = lambda key: list(dict.fromkeys(x for t in ts for x in t[key]))
    d = dict(generic=generic, he=he, kinds=list(kinds), area=ts[0]["area"],
             cls=cls or " + ".join(dict.fromkeys(t["cls"] for t in ts)), brands=brands, suit=suit, why=why,
             thr=u("thr") or ["אין ערך מעבדה ייעודי"], severe=u("severe"), excl=u("excl"),
             comp=[c for t in ts for c in t["comp"]], labs="; ".join(dict.fromkeys(t["labs"] for t in ts)),
             src="; ".join(dict.fromkeys(t["src"] for t in ts)))
    d.update(over)
    d["_t"] = ts
    return d


